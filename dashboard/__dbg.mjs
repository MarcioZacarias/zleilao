import { chromium } from "playwright";
import fs from "node:fs";
const SUB = JSON.parse(fs.readFileSync("sub.json", "utf8"));
const b = await chromium.launch();
const p = await b.newPage();
p.on("pageerror", (e) => console.log("PAGEERROR", e.message));
p.on("console", (m) => m.type() === "error" && console.log("CONSOLE", m.text()));
p.on("response", (r) => r.url().includes("/api/") && console.log("API", r.status(), r.url()));
await p.goto("http://localhost:5178/entrar?next=%2Fbusca%3Fbrand%3DFiat%26criar_alerta%3D1", { waitUntil: "networkidle" });
await p.fill("#email", SUB.email);
await p.fill("#password", SUB.password);
await p.getByRole("button", { name: /^Entrar$/ }).click();
await p.waitForTimeout(4000);
console.log("URL:", p.url());
console.log("erro visivel:", await p.locator("div[role=alert]").count(), await p.locator("div[role=alert]").allInnerTexts());
await b.close();
